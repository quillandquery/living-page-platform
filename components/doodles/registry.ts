/**
 * THE DOODLE LANGUAGE
 *
 * Not illustrations. Not icons. Each doodle is a handful of points in a
 * 100x100 box; the renderer jitters them per instance and smooths them
 * into a stroke, so no two are drawn the same way twice. That is the
 * whole trick: the imperfection is generated, not faked.
 *
 * Add one only when a story needs a thing that isn't here. Resist the
 * urge to build a set.
 */

export type Stroke = [number, number][];
export type DoodleFn = () => Stroke[];

const TAU = Math.PI * 2;

const arc = (cx: number, cy: number, r: number, a0: number, a1: number, n = 14): Stroke => {
  const p: Stroke = [];
  for (let i = 0; i <= n; i++) {
    const a = a0 + ((a1 - a0) * i) / n;
    p.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]);
  }
  return p;
};
const ring = (cx: number, cy: number, r: number, n = 22): Stroke => arc(cx, cy, r, 0, TAU, n);
const wing = (cx: number, cy: number, r: number, n = 9): Stroke =>
  arc(cx, cy, r, Math.PI * 1.15, Math.PI * 1.9, n);

